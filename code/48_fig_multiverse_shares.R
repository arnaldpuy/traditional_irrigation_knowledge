# IRREDUCIBLE SHARES IN THE ORDER OF THE FORKING-PATHS FIGURE ##################

# Load packages ---------------------------------------------------------------

if (!requireNamespace("sensobol", quietly = TRUE)) install.packages("sensobol")
sensobol::load_packages(c("here", "data.table"))

# Read -----------------------------------------------------------------------

grid <- fread(here("datasets", "output", "sobol_headline_grid.csv"))
str(grid)
grid[1:3]
stopifnot(nrow(grid) == 1080L)

# Leaf order -----------------------------------------------------------------

grid[, community := factor(community, levels = c("sudanell", "ricote", "murcia", "oria", "none",
                                                 "durcal", "huetortajar", "arriate"))]
grid[, domain := factor(domain, levels = c("Crop", "Irrigation", "none", "Soil & moisture",
                                           "Weather & climate"))]
grid[, prompt := factor(prompt, levels = c("short", "standard", "strict"))]
grid[, model := factor(model, levels = c("deepseek", "anthropic", "openai"))]
grid[, vote := factor(vote, levels = c("any draw", "majority", "unanimous"))]
stopifnot(!anyNA(grid[, .(community, domain, prompt, model, vote)]))
setorder(grid, community, domain, prompt, model, vote)
ref <- grid[community == "none" & domain == "none" & prompt == "standard" &
              model == "anthropic" & vote == "majority", which = TRUE]
stopifnot(length(ref) == 1L)

# Write ----------------------------------------------------------------------

fwrite(grid[, .(leaf = .I - 1L, community, domain, prompt, model, vote, share)],
       here("datasets", "output", "fig_multiverse_shares.csv"))
writeLines(c("% GENERATED by code/79_fig_multiverse_shares.R -- do not edit by hand",
             sprintf("\\newcommand{\\refleaf}{%d}", ref - 1L),
             sprintf("\\newcommand{\\refshare}{%.0f}", 100 * grid$share[ref]),
             sprintf("\\newcommand{\\shares}{%s}",
                     paste(sprintf("%.3f", grid$share), collapse = ","))),
           here("manuscript", "fig-multiverse-shares.tex"))

# Report ---------------------------------------------------------------------

cat(sprintf("reference specification: leaf %d, %.1f%% irreducible\n",
            ref - 1L, 100 * grid$share[ref]))
cat(sprintf("range across 1,080 specifications: %.1f-%.1f%%\n",
            100 * min(grid$share), 100 * max(grid$share)))
