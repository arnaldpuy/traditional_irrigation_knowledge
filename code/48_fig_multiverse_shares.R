# IRREDUCIBLE SHARES IN THE ORDER OF THE FORKING-PATHS FIGURE ##################

# Load packages ---------------------------------------------------------------

if (!requireNamespace("sensobol", quietly = TRUE)) install.packages("sensobol")
sensobol::load_packages(c("here", "data.table"))

# Read -----------------------------------------------------------------------

shares <- fread(here("datasets", "output", "sobol_headline_grid.csv"))
str(shares)
shares[1:3]
stopifnot(nrow(shares) == 1080L)

# Leaf order -----------------------------------------------------------------

shares[, community := factor(community, levels = c("sudanell", "ricote", "murcia", "oria", "none",
                                                 "durcal", "huetortajar", "arriate"))]
shares[, domain := factor(domain, levels = c("Crop", "Irrigation", "none", "Soil & moisture",
                                           "Weather & climate"))]
shares[, prompt := factor(prompt, levels = c("short", "standard", "strict"))]
shares[, model := factor(model, levels = c("deepseek", "anthropic", "openai"))]
shares[, vote := factor(vote, levels = c("any draw", "majority", "unanimous"))]
stopifnot(!anyNA(shares[, .(community, domain, prompt, model, vote)]))
setorder(shares, community, domain, prompt, model, vote)
ref <- shares[community == "none" & domain == "none" & prompt == "standard" &
              model == "anthropic" & vote == "majority", which = TRUE]
stopifnot(length(ref) == 1L)

# Write ----------------------------------------------------------------------

leaves <- shares[, .(leaf = .I - 1L, community, domain, prompt, model, vote, share)]
fwrite(leaves, here("datasets", "output", "fig_multiverse_shares.csv"))
writeLines(c("% GENERATED by the fig_multiverse_shares script in code/ -- do not edit by hand",
             sprintf("\\newcommand{\\refleaf}{%d}", ref - 1L),
             sprintf("\\newcommand{\\refshare}{%.0f}", 100 * shares$share[ref]),
             sprintf("\\newcommand{\\shares}{%s}",
                     paste(sprintf("%.3f", shares$share), collapse = ","))),
           here("manuscript", "fig-multiverse-shares.tex"))

# Report ---------------------------------------------------------------------

cat(sprintf("reference specification: leaf %d, %.1f%% irreducible\n",
            ref - 1L, 100 * shares$share[ref]))
cat(sprintf("range across 1,080 specifications: %.1f-%.1f%%\n",
            100 * min(shares$share), 100 * max(shares$share)))
